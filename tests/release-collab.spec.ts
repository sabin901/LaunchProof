import { test, expect } from 'deepspace/testing'
import { action, createRelease } from './helpers/actions'

test('invited reviewer updates live; outsider is denied; reconnect preserves evidence', async ({ users }) => {
  const [alice, bob, outsider] = await users(3)
  await bob.page.goto('/home')
  await expect(bob.page.getByTestId('my-user-id')).toHaveText(/\S/)
  const bobId = await bob.page.getByTestId('my-user-id').innerText()
  const id = await createRelease(alice.page)
  await expect(alice.page.getByTestId('gate-card')).toHaveCount(5)
  const gateId = await alice.page.getByTestId('gate-card').first().getAttribute('data-gate-id')
  await outsider.page.goto(`/releases/${id}`)
  await expect(outsider.page.getByRole('heading', { name: 'Release unavailable' })).toBeVisible()
  expect((await action(outsider.page, 'verifyGate', { releaseId: id, gateId, status: 'verified', evidenceNote: 'Forged outsider evidence' })).success).toBe(false)
  expect((await action(alice.page, 'addReviewer', { releaseId: id, targetUserId: bobId })).success).toBe(true)
  await bob.page.goto(`/releases/${id}`)
  await expect(bob.page.getByTestId('gate-card')).toHaveCount(5)
  expect((await action(bob.page, 'addReviewer', { releaseId: id, targetUserId: outsider.userId })).success).toBe(false)
  const card = bob.page.getByTestId('gate-card').first()
  await card.getByRole('button', { name: 'Record evidence' }).click()
  await card.getByLabel('Evidence note').fill('Reviewed the fictional build results together.')
  await card.getByRole('button', { name: 'Save evidence' }).click()
  await expect(alice.page.getByTestId('gate-card').first().getByText('verified', { exact: true })).toBeVisible()
  await expect(alice.page.getByTestId('gate-card').first().getByTestId('verified-by')).toHaveText(bobId)
  await bob.context.setOffline(true)
  await bob.context.setOffline(false)
  await bob.page.reload()
  await expect(bob.page.getByText('Reviewed the fictional build results together.', { exact: true })).toBeVisible()
})
